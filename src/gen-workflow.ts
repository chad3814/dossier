import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { isNoiseAlias } from "./alias-clean.js";
import { normalizeName, readRegistryOrEmpty, toIndex } from "./registry.js";
import { promptMeta, resolveSeriesOrExit } from "./series.js";
import type { SeriesPromptMeta } from "./series.js";
import type { BookManifest, RegistryIndexEntry } from "./types.js";

const START = "// ===== per-book constants";
const END = "// ===================================================";

/** Workflow scripts above this size are rejected by the runner (512 KiB); warn well before it. */
const SCRIPT_SIZE_WARN = 480 * 1024;

/**
 * The known entities that plausibly occur in one chapter: those whose canonical name or any
 * alias appears as whole words (case/punctuation-insensitive) in the chapter text. Replaces
 * handing every chapter agent the whole registry, whose prompt cost grows with the series
 * (see hwfwm/output/token-usage.md). Short (< 3 chars) and stopword forms never qualify.
 */
export function candidateIndex(index: RegistryIndexEntry[], chapterText: string): RegistryIndexEntry[] {
  // Strip possessive 's (straight or curly apostrophe) before normalizing, so "Humphrey's" still
  // matches the name form "humphrey" — normalizeName alone would fold it to "humphreys".
  const text = ` ${normalizeName(chapterText.replace(/[’']s\b/g, ""))} `;
  return index.filter((e) =>
    [e.canonicalName, ...e.aliases]
      .map(normalizeName)
      .some((form) => form.length >= 3 && !isNoiseAlias(form) && text.includes(` ${form} `)),
  );
}

/**
 * Build the per-book constants block the workflow script expects between its markers.
 * `candidatesByFile` maps each section file to the ids of known entities found in it; only
 * those entities are embedded (compactly), so the script stays small however large the series.
 */
export function buildConstants(
  bookNumber: number,
  sectionDir: string,
  sectionFiles: string[],
  startIndex: RegistryIndexEntry[],
  startBooksProcessed: number[],
  series: SeriesPromptMeta,
  candidatesByFile: Record<string, string[]>,
): string {
  const used = new Set(Object.values(candidatesByFile).flat());
  const knownEntities: Record<string, { n: string; a: string[]; t: string }> = {};
  for (const e of startIndex) if (used.has(e.id)) knownEntities[e.id] = { n: e.canonicalName, a: e.aliases, t: e.type };
  return [
    `${START} (generated by gen-workflow.ts) =====`,
    `const bookNumber = ${bookNumber};`,
    `const sectionDir = ${JSON.stringify(sectionDir)};`,
    `const sectionFiles = ${JSON.stringify(sectionFiles)};`,
    `const startIds = ${JSON.stringify(startIndex.map((e) => e.id))};`,
    `const knownEntities = ${JSON.stringify(knownEntities)};`,
    `const candidatesByFile = ${JSON.stringify(candidatesByFile)};`,
    `const startBooksProcessed = ${JSON.stringify(startBooksProcessed)};`,
    `const seriesId = ${JSON.stringify(series.id)};`,
    `const seriesTitle = ${JSON.stringify(series.title)};`,
    `const seriesAuthor = ${JSON.stringify(series.author)};`,
    `const seriesNotes = ${JSON.stringify(series.notes)};`,
    `const agentType = ${JSON.stringify(series.agentType ?? null)};`,
    `const agentModel = ${JSON.stringify(series.model ?? null)};`,
    END,
  ].join("\n");
}

/** Replace the constants block in the workflow script source with a freshly built one. */
export function injectConstants(scriptSource: string, constants: string): string {
  const start = scriptSource.indexOf(START);
  const endMarker = scriptSource.indexOf(END, start);
  if (start === -1 || endMarker === -1) throw new Error("Could not find constants markers in workflow script");
  const end = endMarker + END.length;
  return scriptSource.slice(0, start) + constants + scriptSource.slice(end);
}

function main(): void {
  const here = dirname(fileURLToPath(import.meta.url));
  const repoRoot = join(here, "..");
  const usage = "npm run gen-workflow -- --series <id> <bookNumber>";
  const { paths, profile, rest } = resolveSeriesOrExit(process.argv.slice(2), usage);
  const bookNumber = Number.parseInt(rest[0] ?? "", 10);
  if (!Number.isFinite(bookNumber)) {
    console.error(`usage: ${usage}`);
    process.exit(1);
  }

  const registry = readRegistryOrEmpty(paths.registry); // empty for a series' first book
  const manifest = JSON.parse(readFileSync(paths.manifest(bookNumber), "utf8")) as BookManifest;

  const sectionDir = paths.sectionsDir(bookNumber);
  const sectionFiles = manifest.sections.map((s) => s.file);
  const reprocessing = registry.booksProcessed.includes(bookNumber);
  const startIndex = reprocessing ? [] : toIndex(registry);
  const startBooksProcessed = registry.booksProcessed.filter((b) => b !== bookNumber);

  const candidatesByFile: Record<string, string[]> = {};
  for (const file of sectionFiles) {
    candidatesByFile[file] = candidateIndex(startIndex, readFileSync(join(sectionDir, file), "utf8")).map((e) => e.id);
  }
  const counts = Object.values(candidatesByFile).map((c) => c.length).sort((a, b) => a - b);

  mkdirSync(paths.wfDir, { recursive: true });
  const dest = join(paths.wfDir, "book-extract.js");
  copyFileSync(join(repoRoot, "workflow", "book-extract.js"), dest);
  const constants = buildConstants(
    bookNumber,
    sectionDir,
    sectionFiles,
    startIndex,
    startBooksProcessed,
    promptMeta(profile, "extraction"),
    candidatesByFile,
  );
  const script = injectConstants(readFileSync(dest, "utf8"), constants);
  writeFileSync(dest, script, "utf8");

  const bytes = Buffer.byteLength(script, "utf8");
  console.log(
    `gen-workflow: ${paths.id} book ${bookNumber} — ${sectionFiles.length} sections, ${startIndex.length} prior entities ` +
      `(books ${startBooksProcessed.join(", ") || "none"}); candidates/chapter median ${counts[Math.floor(counts.length / 2)] ?? 0} ` +
      `(max ${counts[counts.length - 1] ?? 0}); script ${(bytes / 1024).toFixed(0)} KB -> ${dest}`,
  );
  if (bytes > SCRIPT_SIZE_WARN) console.warn(`gen-workflow: WARNING script is ${(bytes / 1024).toFixed(0)} KB, near the runner's 512 KB limit`);
}

const invokedDirectly = process.argv[1] === fileURLToPath(import.meta.url);
if (invokedDirectly) main();
